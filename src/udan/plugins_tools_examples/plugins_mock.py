"""Mock tools for testing file rename workflow.

Provides mock implementations of extract_text and tags generation,
simulating what real tools would do for images and PDF files.
"""

from datetime import datetime
from pathlib import Path

from udan.core_tools_loading.api_annotated import annotated

DOMAIN = "mock"

# Maximum number of characters for extract_text output
_MAX_EXTRACT_LENGTH = 1000


@annotated(meta={"attribute_type": "simple", "aliases": ["mock_extract_text"]})
def mock_extract_text(item: str | Path) -> str:
    """Read file content and cut to 1000 characters.

    Simulates text extraction from files (for images/PDFs, a real tool
    would use OCR or PDF parsing libraries).

    Args:
        item: File path as str or Path.

    Returns:
        File content cut to 1000 characters, or empty string if not readable.
    """
    path = Path(item) if isinstance(item, str) else item
    if not path.is_file():
        return ""
    try:
        content = path.read_text(encoding="utf-8", errors="ignore")
        if len(content) > _MAX_EXTRACT_LENGTH:
            content = content[:_MAX_EXTRACT_LENGTH]
        return content
    except OSError:
        return ""


@annotated(meta={"attribute_type": "simple", "aliases": ["file_tags", "mock_tags"]})
def mock_tags(item: str | Path) -> list[str]:
    """Generate tags based on file content using simple keyword matching.

    Simulates tag generation for files. A real tool would use
    NLP/ML models to generate meaningful tags from content.

    Tags are generated by checking for topic keywords in the file content.

    Args:
        item: File path as str or Path.

    Returns:
        List of tag strings (e.g., ["python", "programming", "data-science"]).
    """
    path = Path(item) if isinstance(item, str) else item
    if not path.is_file():
        return []

    try:
        content = path.read_text(encoding="utf-8", errors="ignore").lower()
    except OSError:
        return []

    # Keyword-to-tag mapping
    tag_keywords: dict[str, list[str]] = {
        "python": ["python", "django", "flask", "fastapi", "numpy", "pandas", "scikit-learn"],
        "programming": ["programming", "code", "developer", "software", "algorithm", "function"],
        "data-science": ["data science", "machine learning", "neural network", "statistics"],
        "cooking": ["cooking", "recipe", "kitchen", "baking", "grilling", "frying", "ingredients"],
        "food": ["food", "cuisine", "meal", "dish", "flavor"],
        "travel": ["travel", "destination", "flight", "hotel", "backpack", "tourism"],
        "photography": ["photography", "camera", "photo", "landscape", "portrait"],
        "music": ["music", "song", "guitar", "piano", "jazz", "rock", "electronic"],
        "technology": ["technology", "digital", "software", "hardware", "computer"],
    }

    tags = []
    for tag, keywords in tag_keywords.items():
        if any(keyword in content for keyword in keywords):
            tags.append(tag)

    return tags


@annotated(meta={"attribute_type": "simple"})
def file_headline(item: str | Path, fmt: str = "%Y-%m-%d--%H-%M") -> str:
    """Combine file creation date and filename into a headline string.

    Produces a string like "2026-01-15--12-00 notes_python.txt" suitable
    for use as an org-mode headline.

    Args:
        item: File path as str or Path.
        fmt: Date format string (default: "%Y-%m-%d--%H-%M").

    Returns:
        Combined headline string "date filename", or just filename if date unavailable.
    """
    path = Path(item) if isinstance(item, str) else item
    filename = path.name

    if not path.exists():
        return filename

    try:
        ts = path.stat().st_mtime
        date_str = datetime.fromtimestamp(ts).strftime(fmt)
        return f"{date_str} {filename}"
    except OSError:
        return filename


@annotated(meta={"tool_type": "sorter", "item_type": "str|Path"})
def sort_by_file_created(item: str | Path) -> float:
    """Sort items by file modification time (st_mtime).

    Works with Path objects and string paths. Returns the modification timestamp
    as a float for numeric sorting. Uses st_mtime because on Linux st_ctime
    is metadata change time, not creation time.

    Args:
        item: File path as str or Path.

    Returns:
        File modification timestamp as float, or 0.0 if unavailable.
    """
    path = Path(item) if isinstance(item, str) else item
    if not path.exists():
        return 0.0
    try:
        return path.stat().st_mtime
    except OSError:
        return 0.0
